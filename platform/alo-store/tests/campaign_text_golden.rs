//! The pinned plain-text part and the pinned assembled message (alo Campaigns,
//! ADR 0044, C3.3).
//!
//! The harness is C3.2's, deliberately: same `UPDATE_GOLDENS` switch, same
//! `v1` naming rule, same reason. *The same blocks must produce the same
//! output, so a regression is visible rather than discovered by a customer's
//! recipients* — and a text part fails even more quietly than an HTML one. A
//! table that stopped aligning, a wrap that started breaking URLs, a heading
//! whose underline drifted by one character: none of it throws, and all of it
//! arrives as a letter that looks like it was generated by a machine that did
//! not care.
//!
//! **The letter pinned here is the letter `campaign_html_golden.rs` pins**, so
//! the two files can be read side by side as the two halves of one mail.
//!
//! `campaign_mime_v1_letter.mime` is the whole assembled entity, CRLF and all.
//! It is marked `-text` in `.gitattributes` for the reason the bank fixtures
//! there are: a golden whose line endings git rewrote would stop being the
//! thing the reader is tested against, and in a MIME body the line ending *is*
//! the format.
//!
//! To re-bless after a deliberate change: `UPDATE_GOLDENS=1 cargo nextest run
//! -p alo-store campaign_text_golden`, then **read the diff** — that reading is
//! the test, not the green tick afterwards.

#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::fs;
use std::path::PathBuf;

use alo_store::campaign_unsubscribe_link::UnsubscribeInvitation;
use alo_store::{
    CAMPAIGN_CONTENT_SCHEMA_VERSION, CAMPAIGN_HEADER_LINE_MAX, CAMPAIGN_MIME_LINE_MAX,
    CAMPAIGN_TEXT_WIDTH_COLS, CampaignContent, CampaignLetter, render_campaign_html,
    render_campaign_message, render_campaign_text,
};
use serde_json::{Value, json};

/// The way out the letter must carry (C2.4/C2.5). Not English on purpose: the
/// words belong to the caller, and a golden pinning "Unsubscribe" would read as
/// though they belonged to the renderer.
fn unsub() -> UnsubscribeInvitation {
    UnsubscribeInvitation {
        url: "https://alo.test/u/9tOKENx".to_owned(),
        topic: Some("Nieuwsbrief".to_owned()),
        link_text: "Uitschrijven".to_owned(),
    }
}

fn body(blocks: Value) -> CampaignContent {
    CampaignContent::from_value(json!({
        "schema_version": CAMPAIGN_CONTENT_SCHEMA_VERSION,
        "blocks": blocks,
    }))
    .expect("every fixture in this file must pass the write gate")
}

fn golden_path(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/golden")
        .join(name)
}

fn assert_golden(name: &str, rendered: &str) {
    let path = golden_path(name);
    if std::env::var("UPDATE_GOLDENS").is_ok() {
        fs::create_dir_all(path.parent().expect("a golden lives in a directory"))
            .expect("the golden directory is writable");
        fs::write(&path, rendered).expect("the golden is writable");
        return;
    }
    let expected = fs::read_to_string(&path)
        .unwrap_or_else(|_| panic!("missing golden {name}; run with UPDATE_GOLDENS=1"));
    assert_eq!(
        rendered, expected,
        "{name} drifted; re-bless with UPDATE_GOLDENS=1 and read the diff — a recipient will not \
         tell you which half of the change was the mistake"
    );
}

